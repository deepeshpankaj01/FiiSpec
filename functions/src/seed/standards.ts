const TITLE_NOTE: Verification = {
  status: 'UNVERIFIED',
  note: 'Supersession confirmed from the BIS portal listing on 2026-09-25; the title is given as commonly cited and has not been re-verified.',
};

type StandardInput = Omit<StandardRecord, 'supersedes' | 'versionHistory' | 'amendments' | 'amendmentDataStatus' | 'evidenceReferences' | 'dataOrigin' | 'verification' | 'lifecycle' | 'keywords' | 'productTypes'> &
  Partial<Pick<StandardRecord, 'supersedes' | 'versionHistory' | 'amendments' | 'amendmentDataStatus' | 'evidenceReferences' | 'verification' | 'keywords' | 'productTypes'>>;

function std(input: StandardInput): StandardRecord {
  return {
    supersedes: [],
    versionHistory: input.publicationYear
      ? [{ designation: `${input.standardNumber} : ${input.publicationYear}`, year: input.publicationYear, label: input.edition ?? 'Current edition', status: input.status }]
      : [],
    amendments: [],
    amendmentDataStatus: 'NOT_INDEXED',
    evidenceReferences: [],
    keywords: [],
    productTypes: [],
    verification: UNVERIFIED,
    dataOrigin: 'CURATED_PUBLIC_REFERENCE',
    lifecycle: 'PUBLISHED',
    ...input,
  };
}

const portalAmendment = (standard: string, n: number) => ({
  id: `amd-${n}`,
  number: n,
  summary: `Amendment No. ${n} is listed for ${standard} on the BIS e-Sale portal. Its content is not indexed in FiiSpec.`,
  source: bisPortal(standard.replace(/\s*:.*/, '')),
  verification: UNVERIFIED,
});

