import type { SourceRef, StandardRecord, Verification } from '../../../shared/knowledge';

export const RETRIEVED_AT = '2026-09-25';

export const bisPortal = (query: string, note?: string): SourceRef => ({
  name: 'BIS e-Sale portal — standard listing',
  url: `https://standardsbis.bsbedge.com/BIS_SearchStandard.aspx?Standard_Number=${encodeURIComponent(query)}`,
  retrievedAt: RETRIEVED_AT,
  sourceType: 'BIS_CATALOGUE',
  ...(note ? { note } : {}),
});

